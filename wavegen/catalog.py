"""The preset catalog: ``docs/PRESETS.md``, one entry and thumbnail per preset.

``entries()`` reads the library (bundled presets plus any ``WAVEGEN_PRESET_PATH``
folders), ``tree()`` draws who builds on whom, and ``markdown()`` writes the page.
``wavegen presets catalog`` renders the thumbnails and writes the page.
"""
from __future__ import annotations

from . import config


def _leaves(v) -> int:
    """Values a section sets: nested dicts count their leaves, anything else counts once."""
    if isinstance(v, dict):
        return sum(_leaves(x) for k, x in v.items() if not str(k).startswith("_"))
    return 1


def entries() -> list[dict]:
    """One dict per preset: name, extends, lineage, tags, description, and how many values
    each section of its own file changes (``{"palette": 9, ...}``; empty for a root)."""
    out = []
    for name in config.list_presets():
        info = config.preset_info(name)
        body = config._read(config.find_preset(name))
        own = {k: v for k, v in body.items()
               if k not in config.LIBRARY_KEYS and k != "name" and not k.startswith("_")}
        changes = {k: _leaves(v) for k, v in own.items()} if info["extends"] else {}
        out.append({"name": name, "extends": info["extends"], "lineage": config.lineage(name),
                    "tags": list(info["tags"]), "description": info["description"], "changes": changes})
    return out


def tree(ents: list[dict]) -> str:
    """The family tree as text: roots flush left, each child under its parent."""
    names = {e["name"] for e in ents}
    kids: dict[str | None, list[str]] = {}
    for e in ents:
        parent = e["extends"] if e["extends"] in names else None
        kids.setdefault(parent, []).append(e["name"])
    lines: list[str] = []

    def walk(name: str, prefix: str) -> None:
        cs = sorted(kids.get(name, []))
        for i, c in enumerate(cs):
            last = i == len(cs) - 1
            lines.append(prefix + ("└── " if last else "├── ") + c)
            walk(c, prefix + ("    " if last else "│   "))

    for root in sorted(kids.get(None, [])):
        lines.append(root)
        walk(root, "")
    return "\n".join(lines)


def markdown(ents: list[dict], thumbs: str) -> str:
    """The catalog page. ``thumbs`` is the thumbnail folder relative to the page."""
    md = ["# Preset catalog", "",
          "Every preset in the library, what it builds on and what it changes.",
          "Generated by `python -m wavegen presets catalog`; edit the presets, not this page.", "",
          "## Family tree", "", "```", tree(ents), "```", ""]
    for e in ents:
        md += [f"## {e['name']}", "", f"![{e['name']}]({thumbs}/{e['name']}.jpg)", ""]
        if e["description"]:
            md += [e["description"], ""]
        if e["extends"]:
            md.append(f"- Builds on `{e['extends']}` (lineage: {' -> '.join(e['lineage'])})")
        else:
            md.append("- A root design: every value is its own")
        if e["tags"]:
            md.append(f"- Tags: {', '.join(e['tags'])}")
        if e["changes"]:
            md.append("- Changes: " + ", ".join(f"{k} ({n})" for k, n in e["changes"].items()))
        md.append("")
    return "\n".join(md)
